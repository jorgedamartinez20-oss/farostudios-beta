-- =====================================================================
-- Respaldo completo de la base de datos (estructura + usuarios)
-- Pégalo UNA vez en Supabase → SQL Editor → Run. Se puede correr de nuevo sin problema.
--
-- Crea dos funciones que solo el Worker (con la llave service_role) puede llamar:
--   · faro_respaldo_esquema()  → un archivo SQL con TODA la estructura: extensiones, tablas,
--                                columnas, llaves, índices, funciones, triggers, reglas de seguridad (RLS),
--                                permisos, tareas programadas, buckets y tiempo real.
--   · faro_respaldo_auth()     → los usuarios (auth) tal cual, para restaurarlos con la misma contraseña y MFA.
-- El respaldo diario de las 00:00 las usa para guardar esquema.sql y auth.json en R2.
-- =====================================================================

create or replace function public.faro_respaldo_esquema()
returns text
language plpgsql
security definer
set search_path = pg_catalog, public
as $fn$
declare
  s text := '';
  r record;
  cols text;
begin
  s := '-- Respaldo de la estructura de Supabase (Faro Studios) · generado '
    || to_char(now() at time zone 'America/Guatemala', 'YYYY-MM-DD HH24:MI') || E' (hora de Guatemala)\n'
    || E'-- Restaurar en un proyecto vacío: Supabase → SQL Editor, de arriba abajo. Después cargar los datos (datos/*.json).\n\n'
    || E'set check_function_bodies = off;\nset client_min_messages = warning;\n\n';

  -- Extensiones
  s := s || E'-- ===== Extensiones =====\n';
  for r in select e.extname, n.nspname from pg_extension e join pg_namespace n on n.oid = e.extnamespace
           where e.extname <> 'plpgsql' order by e.extname loop
    s := s || format(E'create extension if not exists %I with schema %I;\n', r.extname, r.nspname);
  end loop;

  -- Tipos enumerados
  s := s || E'\n-- ===== Tipos =====\n';
  for r in select n.nspname, t.typname,
                  (select string_agg(quote_literal(enumlabel), ', ' order by enumsortorder) from pg_enum where enumtypid = t.oid) etiquetas
           from pg_type t join pg_namespace n on n.oid = t.typnamespace
           where n.nspname = 'public' and t.typtype = 'e' order by t.typname loop
    s := s || format(E'do $b$ begin create type %I.%I as enum (%s); exception when duplicate_object or duplicate_table or invalid_table_definition then null; end $b$;\n', r.nspname, r.typname, r.etiquetas);
  end loop;

  -- Secuencias que no pertenecen a una columna de identidad
  s := s || E'\n-- ===== Secuencias =====\n';
  for r in select q.schemaname, q.sequencename, q.data_type::text dt, q.start_value, q.min_value, q.max_value, q.increment_by, q.cycle, q.cache_size
           from pg_sequences q
           where q.schemaname = 'public'
             and not exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
                             join pg_depend d on d.objid = c.oid and d.deptype = 'i'
                             where n.nspname = q.schemaname and c.relname = q.sequencename)
           order by q.sequencename loop
    s := s || format(E'create sequence if not exists %I.%I as %s start with %s increment by %s minvalue %s maxvalue %s cache %s %s;\n',
      r.schemaname, r.sequencename, r.dt, r.start_value, r.increment_by, r.min_value, r.max_value, r.cache_size,
      case when r.cycle then 'cycle' else 'no cycle' end);
  end loop;

  -- Tablas (columnas; los valores por defecto van después de las funciones)
  s := s || E'\n-- ===== Tablas =====\n';
  for r in select c.oid, n.nspname, c.relname, c.relpersistence from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and c.relkind = 'r' order by c.relname loop
    select string_agg(
             '  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
             || case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end
             || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored' else '' end
             || case when a.attnotnull then ' not null' else '' end,
             E',\n' order by a.attnum)
      into cols
      from pg_attribute a
      left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
      where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped;
    s := s || format(E'create %stable if not exists %I.%I (\n%s\n);\n', case when r.relpersistence = 'u' then 'unlogged ' else '' end, r.nspname, r.relname, cols);
  end loop;

  -- Funciones
  s := s || E'\n-- ===== Funciones =====\n';
  for r in select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.prokind in ('f', 'p')
             and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
           order by p.proname, p.oid::int loop
    s := s || pg_get_functiondef(r.oid) || E';\n\n';
  end loop;

  -- Valores por defecto
  s := s || E'-- ===== Valores por defecto =====\n';
  for r in select n.nspname, c.relname, a.attname, pg_get_expr(d.adbin, d.adrelid) ex
           from pg_attrdef d join pg_class c on c.oid = d.adrelid join pg_namespace n on n.oid = c.relnamespace
           join pg_attribute a on a.attrelid = d.adrelid and a.attnum = d.adnum
           where n.nspname = 'public' and c.relkind = 'r' and a.attgenerated = '' order by c.relname, a.attnum loop
    s := s || format(E'alter table %I.%I alter column %I set default %s;\n', r.nspname, r.relname, r.attname, r.ex);
  end loop;

  -- Llaves primarias, únicas y checks
  s := s || E'\n-- ===== Llaves y restricciones =====\n';
  for r in select n.nspname, c.relname, co.conname, pg_get_constraintdef(co.oid) def
           from pg_constraint co join pg_class c on c.oid = co.conrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and c.relkind = 'r' and co.contype in ('p', 'u', 'c', 'x')
           order by c.relname, case co.contype when 'p' then 0 else 1 end, co.conname loop
    s := s || format(E'do $b$ begin alter table %I.%I add constraint %I %s; exception when duplicate_object or duplicate_table or invalid_table_definition then null; end $b$;\n', r.nspname, r.relname, r.conname, r.def);
  end loop;
  -- Llaves foráneas
  for r in select n.nspname, c.relname, co.conname, pg_get_constraintdef(co.oid) def
           from pg_constraint co join pg_class c on c.oid = co.conrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and c.relkind = 'r' and co.contype = 'f' order by c.relname, co.conname loop
    s := s || format(E'do $b$ begin alter table %I.%I add constraint %I %s; exception when duplicate_object or duplicate_table or invalid_table_definition then null; end $b$;\n', r.nspname, r.relname, r.conname, r.def);
  end loop;

  -- Índices
  s := s || E'\n-- ===== Índices =====\n';
  for r in select pg_get_indexdef(i.indexrelid) def
           from pg_index i join pg_class ic on ic.oid = i.indexrelid join pg_class tc on tc.oid = i.indrelid
           join pg_namespace n on n.oid = tc.relnamespace
           where n.nspname = 'public' and tc.relkind = 'r'
             and not exists (select 1 from pg_constraint co where co.conindid = i.indexrelid)
           order by ic.relname loop
    s := s || regexp_replace(r.def, '^CREATE (UNIQUE )?INDEX ', 'CREATE \1INDEX IF NOT EXISTS ') || E';\n';
  end loop;

  -- Vistas
  for r in select n.nspname, c.relname, pg_get_viewdef(c.oid, true) def from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and c.relkind = 'v' order by c.relname loop
    s := s || format(E'create or replace view %I.%I as %s\n', r.nspname, r.relname, r.def);
  end loop;

  -- Triggers
  s := s || E'\n-- ===== Triggers =====\n';
  for r in select n.nspname, c.relname, t.tgname, pg_get_triggerdef(t.oid) def
           from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and not t.tgisinternal order by c.relname, t.tgname loop
    s := s || format(E'drop trigger if exists %I on %I.%I;\n', r.tgname, r.nspname, r.relname) || r.def || E';\n';
  end loop;

  -- Seguridad por filas (RLS) y políticas
  s := s || E'\n-- ===== Seguridad por filas (RLS) =====\n';
  for r in select n.nspname, c.relname, c.relforcerowsecurity from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and c.relkind = 'r' and c.relrowsecurity order by c.relname loop
    s := s || format(E'alter table %I.%I enable row level security;\n', r.nspname, r.relname);
    if r.relforcerowsecurity then s := s || format(E'alter table %I.%I force row level security;\n', r.nspname, r.relname); end if;
  end loop;
  for r in select * from pg_policies where schemaname in ('public', 'storage') order by schemaname, tablename, policyname loop
    s := s || format(E'drop policy if exists %I on %I.%I;\n', r.policyname, r.schemaname, r.tablename)
      || format(E'create policy %I on %I.%I as %s for %s to %s%s%s;\n', r.policyname, r.schemaname, r.tablename, lower(r.permissive), lower(r.cmd),
           array_to_string(r.roles, ', '),
           case when r.qual is not null then E'\n  using (' || r.qual || ')' else '' end,
           case when r.with_check is not null then E'\n  with check (' || r.with_check || ')' else '' end);
  end loop;

  -- Permisos: primero se retiran los de fábrica de cada objeto y luego se conceden los reales (queda exactamente igual)
  s := s || E'\n-- ===== Permisos =====\n';
  for r in select distinct n.nspname, c.relname, c.relkind from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and c.relkind in ('r', 'S', 'v') and c.relacl is not null order by c.relname loop
    s := s || format(E'revoke all on %s %I.%I from public, anon, authenticated, service_role;\n', case when r.relkind = 'S' then 'sequence' else 'table' end, r.nspname, r.relname);
  end loop;
  for r in select p.oid::regprocedure::text firma
           from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.proacl is not null and p.prokind in ('f', 'p')
             and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e') order by 1 loop
    s := s || format(E'revoke all on function %s from public, anon, authenticated, service_role;\n', r.firma);
  end loop;
  for r in select n.nspname, c.relname, c.relkind,
                  case when a.grantee = 0 then 'public' else (select quote_ident(rolname) from pg_roles where oid = a.grantee) end rol,
                  a.is_grantable, string_agg(a.privilege_type, ', ' order by a.privilege_type) privs
           from pg_class c join pg_namespace n on n.oid = c.relnamespace, lateral aclexplode(c.relacl) a
           where n.nspname = 'public' and c.relkind in ('r', 'S', 'v') and c.relacl is not null and a.grantee <> c.relowner
           group by n.nspname, c.relname, c.relkind, a.grantee, a.is_grantable order by c.relname, 4 loop
    s := s || format(E'grant %s on %s %I.%I to %s%s;\n', r.privs, case when r.relkind = 'S' then 'sequence' else 'table' end, r.nspname, r.relname, r.rol,
                     case when r.is_grantable then ' with grant option' else '' end);
  end loop;
  for r in select p.oid::regprocedure::text firma,
                  case when a.grantee = 0 then 'public' else (select quote_ident(rolname) from pg_roles where oid = a.grantee) end rol,
                  a.is_grantable
           from pg_proc p join pg_namespace n on n.oid = p.pronamespace, lateral aclexplode(p.proacl) a
           where n.nspname = 'public' and p.proacl is not null and a.grantee <> p.proowner and p.prokind in ('f', 'p')
             and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
           order by 1, 2 loop
    s := s || format(E'grant execute on function %s to %s%s;\n', r.firma, r.rol, case when r.is_grantable then ' with grant option' else '' end);
  end loop;

  -- Tiempo real
  s := s || E'\n-- ===== Tiempo real =====\n';
  for r in select schemaname, tablename from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' order by tablename loop
    s := s || format(E'do $b$ begin alter publication supabase_realtime add table %I.%I; exception when others then null; end $b$;\n', r.schemaname, r.tablename);
  end loop;

  -- Buckets de Storage
  s := s || E'\n-- ===== Storage (buckets) =====\n';
  for r in select id, name, public, file_size_limit, allowed_mime_types from storage.buckets order by id loop
    s := s || format(E'do $b$ begin insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %L, %L, %L) on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types; exception when others then raise warning ''bucket %s: %%'', sqlerrm; end $b$;\n',
      r.id, r.name, r.public, r.file_size_limit, r.allowed_mime_types, r.id);
  end loop;

  -- Tareas programadas (pg_cron)
  s := s || E'\n-- ===== Tareas programadas =====\n';
  begin
    for r in select jobname, schedule, command from cron.job order by jobid loop
      if r.jobname is null then s := s || format(E'select cron.schedule(%L, %L);\n', r.schedule, r.command);
      else s := s || format(E'select cron.schedule(%L, %L, %L);\n', r.jobname, r.schedule, r.command); end if;
    end loop;
  exception when others then s := s || E'-- (no se pudieron leer las tareas programadas)\n';
  end;

  -- Secretos del Vault: solo los nombres (los valores no se respaldan por seguridad)
  begin
    for r in select name from vault.secrets order by name loop
      s := s || format(E'-- Vault: volver a crear el secreto "%s" con: select vault.create_secret(''<valor>'', %L);\n', r.name, r.name);
    end loop;
  exception when others then null;
  end;

  -- Valores actuales de las secuencias
  s := s || E'\n-- ===== Contadores (secuencias) =====\n';
  for r in select schemaname, sequencename, last_value from pg_sequences where schemaname = 'public' and last_value is not null order by sequencename loop
    s := s || format(E'select setval(%L, %s, true);\n', r.schemaname || '.' || quote_ident(r.sequencename), r.last_value);
  end loop;

  return s || E'\n-- Fin del respaldo de estructura\n';
end;
$fn$;

-- Usuarios (auth): se guardan tal cual para poder restaurarlos con la misma contraseña y el mismo MFA
create or replace function public.faro_respaldo_auth()
returns jsonb
language sql
security definer
set search_path = pg_catalog, public
as $fn$
  select jsonb_build_object(
    'generado', now(),
    'usuarios',     (select coalesce(jsonb_agg(to_jsonb(u)), '[]'::jsonb) from auth.users u),
    'identidades',  (select coalesce(jsonb_agg(to_jsonb(i)), '[]'::jsonb) from auth.identities i),
    'mfa_factores', (select coalesce(jsonb_agg(to_jsonb(f)), '[]'::jsonb) from auth.mfa_factors f)
  );
$fn$;

-- Solo el Worker (service_role) puede llamarlas: contienen la estructura y los datos de acceso
revoke all on function public.faro_respaldo_esquema() from public, anon, authenticated;
revoke all on function public.faro_respaldo_auth() from public, anon, authenticated;
grant execute on function public.faro_respaldo_esquema() to service_role;
grant execute on function public.faro_respaldo_auth() to service_role;
